local SKIP = { reset33 = true, barsToggled = true, chatSetupDone = true, positions = true,
    raidImportantIcons = true }

local function Merge(dst, src)
    for k, v in pairs(src) do
        if type(v) == "table" then
            if type(dst[k]) ~= "table" then dst[k] = {} end
            Merge(dst[k], v)
        else
            dst[k] = v
        end
    end
end

for k, v in pairs(profile) do
    if not SKIP[k] and not (type(k) == "string" and k:find("^v%d+$")) then
        if k == "colorPicker" and type(v) == "table" then
            v.history, v.favorite = nil, nil
        end
        if type(v) == "table" then
            if type(A.defaults[k]) ~= "table" then A.defaults[k] = {} end
            Merge(A.defaults[k], v)
        else
            A.defaults[k] = v
        end
    end
end

-- positions the profile moved
for key, p in pairs(profile.positions or {}) do
    A.defaultPositions[key] = { p[1], p[2], p[3], p[4] }
end
A.defaultProfile = profile
